    def test_h02_bayesian_reliability_asymmetry(self):
        """H-02: Bayesian reliability enforces beta=0.50 failure asymmetry (failure penalizes twice as much)."""
        # Equal attempts: 1 success vs 1 failure
        # Baseline neutral prior (0s, 0f): (1 + 0) / (2 + 0 + 0) = 1 / 2 = 0.50
        # R(1s, 0f) with weight 1.0: (1 + 1) / (2 + 1 + 0) = 2 / 3 = 0.6667 (+0.1667)
        # R(0s, 1f) with weight 1.0: (1 + 0) / (2 + 0 + 2*1) = 1 / 4 = 0.25 (-0.2500)
        r_prior = calculate_bayesian_strategy_reliability(0.0, 0.0)
        r_succ = calculate_bayesian_strategy_reliability(1.0, 0.0)
        r_fail = calculate_bayesian_strategy_reliability(0.0, 1.0)

        self.assertAlmostEqual(r_prior, 0.50, places=3)
        self.assertAlmostEqual(r_succ, 2.0 / 3.0, places=3)
        self.assertAlmostEqual(r_fail, 0.25, places=3)

        # Failure penalty drops reliability further below prior than success raises above prior
        self.assertGreater(r_prior - r_fail, r_succ - r_prior)

